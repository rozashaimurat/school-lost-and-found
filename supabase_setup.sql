-- 1. The items table
create table if not exists public.items (
  id               bigint generated by default as identity primary key,
  slot_number      int,
  holding_location text not null default 'Front Office',
  item_type        text not null,
  location_found   text not null,
  date_found       date not null,
  notes            text,
  image_path       text,
  pickup_room      text,
  status           text not null default 'pending',   -- 'pending' or 'approved'
  reported         boolean not null default false,
  report_reason    text,
  is_returned      boolean not null default false,
  claimed_by       text,
  returned_at      timestamptz,
  created_at       timestamptz not null default now()
);

-- Lock the table: only the app (using the secret key) can read or write it.
alter table public.items enable row level security;

-- 2. Add an item and give it the lowest free office slot.
--    The lock makes sure two people saving at the same moment never get the same slot.
create or replace function public.add_item(
  p_holding text, p_item_type text, p_location text, p_date date,
  p_notes text, p_pickup_room text, p_status text
) returns public.items
language plpgsql as $$
declare
  new_slot int;
  rec public.items;
begin
  perform pg_advisory_xact_lock(424242);
  if p_holding = 'Front Office' then
    select min(s) into new_slot
    from generate_series(
      1,
      (select count(*) + 1 from public.items
        where is_returned = false and holding_location = 'Front Office' and slot_number is not null)::int
    ) as s
    where s not in (
      select slot_number from public.items
      where is_returned = false and holding_location = 'Front Office' and slot_number is not null
    );
  end if;
  insert into public.items
    (slot_number, holding_location, item_type, location_found, date_found, notes, pickup_room, status)
  values
    (new_slot, p_holding, p_item_type, p_location, p_date, p_notes, p_pickup_room, p_status)
  returning * into rec;
  return rec;
end;
$$;

revoke execute on function public.add_item(text, text, text, date, text, text, text) from public, anon, authenticated;
grant execute on function public.add_item(text, text, text, date, text, text, text) to service_role;

